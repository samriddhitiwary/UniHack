"""Explicit evaluation states and field group taxonomy."""

from enum import StrEnum


class EvaluationMatchStatus(StrEnum):
    EXACT_MATCH = "EXACT_MATCH"
    NORMALIZED_MATCH = "NORMALIZED_MATCH"
    MISMATCH = "MISMATCH"
    EXPECTED_POPULATED_ACTUAL_BLANK = "EXPECTED_POPULATED_ACTUAL_BLANK"
    EXPECTED_BLANK_ACTUAL_POPULATED = "EXPECTED_BLANK_ACTUAL_POPULATED"
    BOTH_BLANK = "BOTH_BLANK"
    NOT_EVALUATED = "NOT_EVALUATED"


class UnilogFieldGroup(StrEnum):
    IDENTITY = "IDENTITY"
    CLASSIFICATION = "CLASSIFICATION"
    DESCRIPTION = "DESCRIPTION"
    FEATURE = "FEATURE"
    ATTRIBUTE = "ATTRIBUTE"
    COMMERCIAL = "COMMERCIAL"
    DIMENSION = "DIMENSION"
    ASSET = "ASSET"
    DOCUMENT = "DOCUMENT"
    REFERENCE = "REFERENCE"
    OTHER = "OTHER"


class ConfidenceBand(StrEnum):
    HIGH = "HIGH"
    MEDIUM = "MEDIUM"
    LOW = "LOW"


class FieldIssueType(StrEnum):
    MISMATCH = "MISMATCH"
    MISSING_EXPECTED = "MISSING_EXPECTED"
    UNEXPECTED_POPULATED = "UNEXPECTED_POPULATED"
    NORMALIZED_ONLY = "NORMALIZED_ONLY"
